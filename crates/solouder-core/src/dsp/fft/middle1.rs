use super::{CDFT_LOOP_DIV, M_PI_2, WR5000};

pub(super) fn cftmdl1(n: isize, a: &mut [f32]) {
    let mut i: isize = 0;
    let mut i0: isize = 0;
    let mut j: isize = 0;
    let mut j0: isize = 0;
    let mut j1: isize = 0;
    let mut j2: isize = 0;
    let mut j3: isize = 0;
    let mut m: isize = 0;
    let mut mh: isize = 0;
    let mut ew: f32 = 0.0;
    let mut w1r: f32 = 0.0;
    let mut w1i: f32 = 0.0;
    let mut wk1r: f32 = 0.0;
    let mut wk1i: f32 = 0.0;
    let mut wk3r: f32 = 0.0;
    let mut wk3i: f32 = 0.0;
    let mut wd1r: f32 = 0.0;
    let mut wd1i: f32 = 0.0;
    let mut wd3r: f32 = 0.0;
    let mut wd3i: f32 = 0.0;
    let mut ss1: f32 = 0.0;
    let mut ss3: f32 = 0.0;
    let mut x0r: f32 = 0.0;
    let mut x0i: f32 = 0.0;
    let mut x1r: f32 = 0.0;
    let mut x1i: f32 = 0.0;
    let mut x2r: f32 = 0.0;
    let mut x2i: f32 = 0.0;
    let mut x3r: f32 = 0.0;
    let mut x3i: f32 = 0.0;
    mh = n >> 3;
    m = 2 * mh;
    j1 = m;
    j2 = j1 + m;
    j3 = j2 + m;
    x0r = a[0] + a[j2 as usize];
    x0i = a[1] + a[(j2 + 1) as usize];
    x1r = a[0] - a[j2 as usize];
    x1i = a[1] - a[(j2 + 1) as usize];
    x2r = a[j1 as usize] + a[j3 as usize];
    x2i = a[(j1 + 1) as usize] + a[(j3 + 1) as usize];
    x3r = a[j1 as usize] - a[j3 as usize];
    x3i = a[(j1 + 1) as usize] - a[(j3 + 1) as usize];
    a[0] = x0r + x2r;
    a[1] = x0i + x2i;
    a[j1 as usize] = x0r - x2r;
    a[(j1 + 1) as usize] = x0i - x2i;
    a[j2 as usize] = x1r - x3i;
    a[(j2 + 1) as usize] = x1i + x3r;
    a[j3 as usize] = x1r + x3i;
    a[(j3 + 1) as usize] = x1i - x3r;
    wd1r = 1.0;
    wd1i = 0.0;
    wd3r = 1.0;
    wd3i = 0.0;
    ew = M_PI_2 / (m as f32);
    w1r = f64::from(2.0 * ew).cos() as f32;
    w1i = f64::from(2.0 * ew).sin() as f32;
    wk1r = w1r;
    wk1i = w1i;
    ss1 = 2.0 * w1i;
    wk3i = 2.0 * ss1 * wk1r;
    wk3r = wk1r - wk3i * wk1i;
    wk3i = wk1i - wk3i * wk1r;
    ss3 = 2.0 * wk3i;
    i = 0;
    loop {
        i0 = i + 4 * CDFT_LOOP_DIV;
        if i0 > mh - 4 {
            i0 = mh - 4;
        }
        j = i + 2;
        while j < i0 {
            wd1r -= ss1 * wk1i;
            wd1i += ss1 * wk1r;
            wd3r -= ss3 * wk3i;
            wd3i += ss3 * wk3r;
            j1 = j + m;
            j2 = j1 + m;
            j3 = j2 + m;
            x0r = a[j as usize] + a[j2 as usize];
            x0i = a[(j + 1) as usize] + a[(j2 + 1) as usize];
            x1r = a[j as usize] - a[j2 as usize];
            x1i = a[(j + 1) as usize] - a[(j2 + 1) as usize];
            x2r = a[j1 as usize] + a[j3 as usize];
            x2i = a[(j1 + 1) as usize] + a[(j3 + 1) as usize];
            x3r = a[j1 as usize] - a[j3 as usize];
            x3i = a[(j1 + 1) as usize] - a[(j3 + 1) as usize];
            a[j as usize] = x0r + x2r;
            a[(j + 1) as usize] = x0i + x2i;
            a[j1 as usize] = x0r - x2r;
            a[(j1 + 1) as usize] = x0i - x2i;
            x0r = x1r - x3i;
            x0i = x1i + x3r;
            a[j2 as usize] = wk1r * x0r - wk1i * x0i;
            a[(j2 + 1) as usize] = wk1r * x0i + wk1i * x0r;
            x0r = x1r + x3i;
            x0i = x1i - x3r;
            a[j3 as usize] = wk3r * x0r + wk3i * x0i;
            a[(j3 + 1) as usize] = wk3r * x0i - wk3i * x0r;
            x0r = a[(j + 2) as usize] + a[(j2 + 2) as usize];
            x0i = a[(j + 3) as usize] + a[(j2 + 3) as usize];
            x1r = a[(j + 2) as usize] - a[(j2 + 2) as usize];
            x1i = a[(j + 3) as usize] - a[(j2 + 3) as usize];
            x2r = a[(j1 + 2) as usize] + a[(j3 + 2) as usize];
            x2i = a[(j1 + 3) as usize] + a[(j3 + 3) as usize];
            x3r = a[(j1 + 2) as usize] - a[(j3 + 2) as usize];
            x3i = a[(j1 + 3) as usize] - a[(j3 + 3) as usize];
            a[(j + 2) as usize] = x0r + x2r;
            a[(j + 3) as usize] = x0i + x2i;
            a[(j1 + 2) as usize] = x0r - x2r;
            a[(j1 + 3) as usize] = x0i - x2i;
            x0r = x1r - x3i;
            x0i = x1i + x3r;
            a[(j2 + 2) as usize] = wd1r * x0r - wd1i * x0i;
            a[(j2 + 3) as usize] = wd1r * x0i + wd1i * x0r;
            x0r = x1r + x3i;
            x0i = x1i - x3r;
            a[(j3 + 2) as usize] = wd3r * x0r + wd3i * x0i;
            a[(j3 + 3) as usize] = wd3r * x0i - wd3i * x0r;
            j0 = m - j;
            j1 = j0 + m;
            j2 = j1 + m;
            j3 = j2 + m;
            x0r = a[j0 as usize] + a[j2 as usize];
            x0i = a[(j0 + 1) as usize] + a[(j2 + 1) as usize];
            x1r = a[j0 as usize] - a[j2 as usize];
            x1i = a[(j0 + 1) as usize] - a[(j2 + 1) as usize];
            x2r = a[j1 as usize] + a[j3 as usize];
            x2i = a[(j1 + 1) as usize] + a[(j3 + 1) as usize];
            x3r = a[j1 as usize] - a[j3 as usize];
            x3i = a[(j1 + 1) as usize] - a[(j3 + 1) as usize];
            a[j0 as usize] = x0r + x2r;
            a[(j0 + 1) as usize] = x0i + x2i;
            a[j1 as usize] = x0r - x2r;
            a[(j1 + 1) as usize] = x0i - x2i;
            x0r = x1r - x3i;
            x0i = x1i + x3r;
            a[j2 as usize] = wk1i * x0r - wk1r * x0i;
            a[(j2 + 1) as usize] = wk1i * x0i + wk1r * x0r;
            x0r = x1r + x3i;
            x0i = x1i - x3r;
            a[j3 as usize] = wk3i * x0r + wk3r * x0i;
            a[(j3 + 1) as usize] = wk3i * x0i - wk3r * x0r;
            x0r = a[(j0 - 2) as usize] + a[(j2 - 2) as usize];
            x0i = a[(j0 - 1) as usize] + a[(j2 - 1) as usize];
            x1r = a[(j0 - 2) as usize] - a[(j2 - 2) as usize];
            x1i = a[(j0 - 1) as usize] - a[(j2 - 1) as usize];
            x2r = a[(j1 - 2) as usize] + a[(j3 - 2) as usize];
            x2i = a[(j1 - 1) as usize] + a[(j3 - 1) as usize];
            x3r = a[(j1 - 2) as usize] - a[(j3 - 2) as usize];
            x3i = a[(j1 - 1) as usize] - a[(j3 - 1) as usize];
            a[(j0 - 2) as usize] = x0r + x2r;
            a[(j0 - 1) as usize] = x0i + x2i;
            a[(j1 - 2) as usize] = x0r - x2r;
            a[(j1 - 1) as usize] = x0i - x2i;
            x0r = x1r - x3i;
            x0i = x1i + x3r;
            a[(j2 - 2) as usize] = wd1i * x0r - wd1r * x0i;
            a[(j2 - 1) as usize] = wd1i * x0i + wd1r * x0r;
            x0r = x1r + x3i;
            x0i = x1i - x3r;
            a[(j3 - 2) as usize] = wd3i * x0r + wd3r * x0i;
            a[(j3 - 1) as usize] = wd3i * x0i - wd3r * x0r;
            wk1r -= ss1 * wd1i;
            wk1i += ss1 * wd1r;
            wk3r -= ss3 * wd3i;
            wk3i += ss3 * wd3r;
            j += 4;
        }
        if i0 == mh - 4 {
            break;
        }
        wd1r = f64::from(ew * (i0 as f32)).cos() as f32;
        wd1i = f64::from(ew * (i0 as f32)).sin() as f32;
        wd3i = 4.0 * wd1i * wd1r;
        wd3r = wd1r - wd3i * wd1i;
        wd3i = wd1i - wd3i * wd1r;
        wk1r = w1r * wd1r - w1i * wd1i;
        wk1i = w1r * wd1i + w1i * wd1r;
        wk3i = 4.0 * wk1i * wk1r;
        wk3r = wk1r - wk3i * wk1i;
        wk3i = wk1i - wk3i * wk1r;
        i = i0;
    }
    wd1r = WR5000;
    j0 = mh;
    j1 = j0 + m;
    j2 = j1 + m;
    j3 = j2 + m;
    x0r = a[(j0 - 2) as usize] + a[(j2 - 2) as usize];
    x0i = a[(j0 - 1) as usize] + a[(j2 - 1) as usize];
    x1r = a[(j0 - 2) as usize] - a[(j2 - 2) as usize];
    x1i = a[(j0 - 1) as usize] - a[(j2 - 1) as usize];
    x2r = a[(j1 - 2) as usize] + a[(j3 - 2) as usize];
    x2i = a[(j1 - 1) as usize] + a[(j3 - 1) as usize];
    x3r = a[(j1 - 2) as usize] - a[(j3 - 2) as usize];
    x3i = a[(j1 - 1) as usize] - a[(j3 - 1) as usize];
    a[(j0 - 2) as usize] = x0r + x2r;
    a[(j0 - 1) as usize] = x0i + x2i;
    a[(j1 - 2) as usize] = x0r - x2r;
    a[(j1 - 1) as usize] = x0i - x2i;
    x0r = x1r - x3i;
    x0i = x1i + x3r;
    a[(j2 - 2) as usize] = wk1r * x0r - wk1i * x0i;
    a[(j2 - 1) as usize] = wk1r * x0i + wk1i * x0r;
    x0r = x1r + x3i;
    x0i = x1i - x3r;
    a[(j3 - 2) as usize] = wk3r * x0r + wk3i * x0i;
    a[(j3 - 1) as usize] = wk3r * x0i - wk3i * x0r;
    x0r = a[j0 as usize] + a[j2 as usize];
    x0i = a[(j0 + 1) as usize] + a[(j2 + 1) as usize];
    x1r = a[j0 as usize] - a[j2 as usize];
    x1i = a[(j0 + 1) as usize] - a[(j2 + 1) as usize];
    x2r = a[j1 as usize] + a[j3 as usize];
    x2i = a[(j1 + 1) as usize] + a[(j3 + 1) as usize];
    x3r = a[j1 as usize] - a[j3 as usize];
    x3i = a[(j1 + 1) as usize] - a[(j3 + 1) as usize];
    a[j0 as usize] = x0r + x2r;
    a[(j0 + 1) as usize] = x0i + x2i;
    a[j1 as usize] = x0r - x2r;
    a[(j1 + 1) as usize] = x0i - x2i;
    x0r = x1r - x3i;
    x0i = x1i + x3r;
    a[j2 as usize] = wd1r * (x0r - x0i);
    a[(j2 + 1) as usize] = wd1r * (x0i + x0r);
    x0r = x1r + x3i;
    x0i = x1i - x3r;
    a[j3 as usize] = -wd1r * (x0r + x0i);
    a[(j3 + 1) as usize] = -wd1r * (x0i - x0r);
    x0r = a[(j0 + 2) as usize] + a[(j2 + 2) as usize];
    x0i = a[(j0 + 3) as usize] + a[(j2 + 3) as usize];
    x1r = a[(j0 + 2) as usize] - a[(j2 + 2) as usize];
    x1i = a[(j0 + 3) as usize] - a[(j2 + 3) as usize];
    x2r = a[(j1 + 2) as usize] + a[(j3 + 2) as usize];
    x2i = a[(j1 + 3) as usize] + a[(j3 + 3) as usize];
    x3r = a[(j1 + 2) as usize] - a[(j3 + 2) as usize];
    x3i = a[(j1 + 3) as usize] - a[(j3 + 3) as usize];
    a[(j0 + 2) as usize] = x0r + x2r;
    a[(j0 + 3) as usize] = x0i + x2i;
    a[(j1 + 2) as usize] = x0r - x2r;
    a[(j1 + 3) as usize] = x0i - x2i;
    x0r = x1r - x3i;
    x0i = x1i + x3r;
    a[(j2 + 2) as usize] = wk1i * x0r - wk1r * x0i;
    a[(j2 + 3) as usize] = wk1i * x0i + wk1r * x0r;
    x0r = x1r + x3i;
    x0i = x1i - x3r;
    a[(j3 + 2) as usize] = wk3i * x0r + wk3r * x0i;
    a[(j3 + 3) as usize] = wk3i * x0i - wk3r * x0r;
}

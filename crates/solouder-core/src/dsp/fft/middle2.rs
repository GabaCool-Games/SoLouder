use super::{CDFT_LOOP_DIV, M_PI_2, WI2500, WR2500, WR5000};

pub(super) fn cftmdl2(n: isize, a: &mut [f32]) {
    let mut i: isize = 0;
    let mut i0: isize = 0;
    let mut j: isize = 0;
    let mut j0: isize = 0;
    let mut j1: isize = 0;
    let mut j2: isize = 0;
    let mut j3: isize = 0;
    let mut m: isize = 0;
    let mut mh: isize = 0;
    let mut ew: f32 = 0.0;
    let mut w1r: f32 = 0.0;
    let mut w1i: f32 = 0.0;
    let mut wn4r: f32 = 0.0;
    let mut wk1r: f32 = 0.0;
    let mut wk1i: f32 = 0.0;
    let mut wk3r: f32 = 0.0;
    let mut wk3i: f32 = 0.0;
    let mut wl1r: f32 = 0.0;
    let mut wl1i: f32 = 0.0;
    let mut wl3r: f32 = 0.0;
    let mut wl3i: f32 = 0.0;
    let mut wd1r: f32 = 0.0;
    let mut wd1i: f32 = 0.0;
    let mut wd3r: f32 = 0.0;
    let mut wd3i: f32 = 0.0;
    let mut we1r: f32 = 0.0;
    let mut we1i: f32 = 0.0;
    let mut we3r: f32 = 0.0;
    let mut we3i: f32 = 0.0;
    let mut ss1: f32 = 0.0;
    let mut ss3: f32 = 0.0;
    let mut x0r: f32 = 0.0;
    let mut x0i: f32 = 0.0;
    let mut x1r: f32 = 0.0;
    let mut x1i: f32 = 0.0;
    let mut x2r: f32 = 0.0;
    let mut x2i: f32 = 0.0;
    let mut x3r: f32 = 0.0;
    let mut x3i: f32 = 0.0;
    let mut y0r: f32 = 0.0;
    let mut y0i: f32 = 0.0;
    let mut y2r: f32 = 0.0;
    let mut y2i: f32 = 0.0;
    mh = n >> 3;
    m = 2 * mh;
    wn4r = WR5000;
    j1 = m;
    j2 = j1 + m;
    j3 = j2 + m;
    x0r = a[0] - a[(j2 + 1) as usize];
    x0i = a[1] + a[j2 as usize];
    x1r = a[0] + a[(j2 + 1) as usize];
    x1i = a[1] - a[j2 as usize];
    x2r = a[j1 as usize] - a[(j3 + 1) as usize];
    x2i = a[(j1 + 1) as usize] + a[j3 as usize];
    x3r = a[j1 as usize] + a[(j3 + 1) as usize];
    x3i = a[(j1 + 1) as usize] - a[j3 as usize];
    y0r = wn4r * (x2r - x2i);
    y0i = wn4r * (x2i + x2r);
    a[0] = x0r + y0r;
    a[1] = x0i + y0i;
    a[j1 as usize] = x0r - y0r;
    a[(j1 + 1) as usize] = x0i - y0i;
    y0r = wn4r * (x3r - x3i);
    y0i = wn4r * (x3i + x3r);
    a[j2 as usize] = x1r - y0i;
    a[(j2 + 1) as usize] = x1i + y0r;
    a[j3 as usize] = x1r + y0i;
    a[(j3 + 1) as usize] = x1i - y0r;
    wl1r = 1.0;
    wl1i = 0.0;
    wl3r = 1.0;
    wl3i = 0.0;
    we1r = wn4r;
    we1i = wn4r;
    we3r = -wn4r;
    we3i = -wn4r;
    ew = M_PI_2 / (2.0 * (m as f32));
    w1r = f64::from(2.0 * ew).cos() as f32;
    w1i = f64::from(2.0 * ew).sin() as f32;
    wk1r = w1r;
    wk1i = w1i;
    wd1r = wn4r * (w1r - w1i);
    wd1i = wn4r * (w1i + w1r);
    ss1 = 2.0 * w1i;
    wk3i = 2.0 * ss1 * wk1r;
    wk3r = wk1r - wk3i * wk1i;
    wk3i = wk1i - wk3i * wk1r;
    ss3 = 2.0 * wk3i;
    wd3r = -wn4r * (wk3r - wk3i);
    wd3i = -wn4r * (wk3i + wk3r);
    i = 0;
    loop {
        i0 = i + 4 * CDFT_LOOP_DIV;
        if i0 > mh - 4 {
            i0 = mh - 4;
        }
        j = i + 2;
        while j < i0 {
            wl1r -= ss1 * wk1i;
            wl1i += ss1 * wk1r;
            wl3r -= ss3 * wk3i;
            wl3i += ss3 * wk3r;
            we1r -= ss1 * wd1i;
            we1i += ss1 * wd1r;
            we3r -= ss3 * wd3i;
            we3i += ss3 * wd3r;
            j1 = j + m;
            j2 = j1 + m;
            j3 = j2 + m;
            x0r = a[j as usize] - a[(j2 + 1) as usize];
            x0i = a[(j + 1) as usize] + a[j2 as usize];
            x1r = a[j as usize] + a[(j2 + 1) as usize];
            x1i = a[(j + 1) as usize] - a[j2 as usize];
            x2r = a[j1 as usize] - a[(j3 + 1) as usize];
            x2i = a[(j1 + 1) as usize] + a[j3 as usize];
            x3r = a[j1 as usize] + a[(j3 + 1) as usize];
            x3i = a[(j1 + 1) as usize] - a[j3 as usize];
            y0r = wk1r * x0r - wk1i * x0i;
            y0i = wk1r * x0i + wk1i * x0r;
            y2r = wd1r * x2r - wd1i * x2i;
            y2i = wd1r * x2i + wd1i * x2r;
            a[j as usize] = y0r + y2r;
            a[(j + 1) as usize] = y0i + y2i;
            a[j1 as usize] = y0r - y2r;
            a[(j1 + 1) as usize] = y0i - y2i;
            y0r = wk3r * x1r + wk3i * x1i;
            y0i = wk3r * x1i - wk3i * x1r;
            y2r = wd3r * x3r + wd3i * x3i;
            y2i = wd3r * x3i - wd3i * x3r;
            a[j2 as usize] = y0r + y2r;
            a[(j2 + 1) as usize] = y0i + y2i;
            a[j3 as usize] = y0r - y2r;
            a[(j3 + 1) as usize] = y0i - y2i;
            x0r = a[(j + 2) as usize] - a[(j2 + 3) as usize];
            x0i = a[(j + 3) as usize] + a[(j2 + 2) as usize];
            x1r = a[(j + 2) as usize] + a[(j2 + 3) as usize];
            x1i = a[(j + 3) as usize] - a[(j2 + 2) as usize];
            x2r = a[(j1 + 2) as usize] - a[(j3 + 3) as usize];
            x2i = a[(j1 + 3) as usize] + a[(j3 + 2) as usize];
            x3r = a[(j1 + 2) as usize] + a[(j3 + 3) as usize];
            x3i = a[(j1 + 3) as usize] - a[(j3 + 2) as usize];
            y0r = wl1r * x0r - wl1i * x0i;
            y0i = wl1r * x0i + wl1i * x0r;
            y2r = we1r * x2r - we1i * x2i;
            y2i = we1r * x2i + we1i * x2r;
            a[(j + 2) as usize] = y0r + y2r;
            a[(j + 3) as usize] = y0i + y2i;
            a[(j1 + 2) as usize] = y0r - y2r;
            a[(j1 + 3) as usize] = y0i - y2i;
            y0r = wl3r * x1r + wl3i * x1i;
            y0i = wl3r * x1i - wl3i * x1r;
            y2r = we3r * x3r + we3i * x3i;
            y2i = we3r * x3i - we3i * x3r;
            a[(j2 + 2) as usize] = y0r + y2r;
            a[(j2 + 3) as usize] = y0i + y2i;
            a[(j3 + 2) as usize] = y0r - y2r;
            a[(j3 + 3) as usize] = y0i - y2i;
            j0 = m - j;
            j1 = j0 + m;
            j2 = j1 + m;
            j3 = j2 + m;
            x0r = a[j0 as usize] - a[(j2 + 1) as usize];
            x0i = a[(j0 + 1) as usize] + a[j2 as usize];
            x1r = a[j0 as usize] + a[(j2 + 1) as usize];
            x1i = a[(j0 + 1) as usize] - a[j2 as usize];
            x2r = a[j1 as usize] - a[(j3 + 1) as usize];
            x2i = a[(j1 + 1) as usize] + a[j3 as usize];
            x3r = a[j1 as usize] + a[(j3 + 1) as usize];
            x3i = a[(j1 + 1) as usize] - a[j3 as usize];
            y0r = wd1i * x0r - wd1r * x0i;
            y0i = wd1i * x0i + wd1r * x0r;
            y2r = wk1i * x2r - wk1r * x2i;
            y2i = wk1i * x2i + wk1r * x2r;
            a[j0 as usize] = y0r + y2r;
            a[(j0 + 1) as usize] = y0i + y2i;
            a[j1 as usize] = y0r - y2r;
            a[(j1 + 1) as usize] = y0i - y2i;
            y0r = wd3i * x1r + wd3r * x1i;
            y0i = wd3i * x1i - wd3r * x1r;
            y2r = wk3i * x3r + wk3r * x3i;
            y2i = wk3i * x3i - wk3r * x3r;
            a[j2 as usize] = y0r + y2r;
            a[(j2 + 1) as usize] = y0i + y2i;
            a[j3 as usize] = y0r - y2r;
            a[(j3 + 1) as usize] = y0i - y2i;
            x0r = a[(j0 - 2) as usize] - a[(j2 - 1) as usize];
            x0i = a[(j0 - 1) as usize] + a[(j2 - 2) as usize];
            x1r = a[(j0 - 2) as usize] + a[(j2 - 1) as usize];
            x1i = a[(j0 - 1) as usize] - a[(j2 - 2) as usize];
            x2r = a[(j1 - 2) as usize] - a[(j3 - 1) as usize];
            x2i = a[(j1 - 1) as usize] + a[(j3 - 2) as usize];
            x3r = a[(j1 - 2) as usize] + a[(j3 - 1) as usize];
            x3i = a[(j1 - 1) as usize] - a[(j3 - 2) as usize];
            y0r = we1i * x0r - we1r * x0i;
            y0i = we1i * x0i + we1r * x0r;
            y2r = wl1i * x2r - wl1r * x2i;
            y2i = wl1i * x2i + wl1r * x2r;
            a[(j0 - 2) as usize] = y0r + y2r;
            a[(j0 - 1) as usize] = y0i + y2i;
            a[(j1 - 2) as usize] = y0r - y2r;
            a[(j1 - 1) as usize] = y0i - y2i;
            y0r = we3i * x1r + we3r * x1i;
            y0i = we3i * x1i - we3r * x1r;
            y2r = wl3i * x3r + wl3r * x3i;
            y2i = wl3i * x3i - wl3r * x3r;
            a[(j2 - 2) as usize] = y0r + y2r;
            a[(j2 - 1) as usize] = y0i + y2i;
            a[(j3 - 2) as usize] = y0r - y2r;
            a[(j3 - 1) as usize] = y0i - y2i;
            wk1r -= ss1 * wl1i;
            wk1i += ss1 * wl1r;
            wk3r -= ss3 * wl3i;
            wk3i += ss3 * wl3r;
            wd1r -= ss1 * we1i;
            wd1i += ss1 * we1r;
            wd3r -= ss3 * we3i;
            wd3i += ss3 * we3r;
            j += 4;
        }
        if i0 == mh - 4 {
            break;
        }
        wl1r = f64::from(ew * (i0 as f32)).cos() as f32;
        wl1i = f64::from(ew * (i0 as f32)).sin() as f32;
        wl3i = 4.0 * wl1i * wl1r;
        wl3r = wl1r - wl3i * wl1i;
        wl3i = wl1i - wl3i * wl1r;
        we1r = wn4r * (wl1r - wl1i);
        we1i = wn4r * (wl1i + wl1r);
        we3r = -wn4r * (wl3r - wl3i);
        we3i = -wn4r * (wl3i + wl3r);
        wk1r = w1r * wl1r - w1i * wl1i;
        wk1i = w1r * wl1i + w1i * wl1r;
        wk3i = 4.0 * wk1i * wk1r;
        wk3r = wk1r - wk3i * wk1i;
        wk3i = wk1i - wk3i * wk1r;
        wd1r = wn4r * (wk1r - wk1i);
        wd1i = wn4r * (wk1i + wk1r);
        wd3r = -wn4r * (wk3r - wk3i);
        wd3i = -wn4r * (wk3i + wk3r);
        i = i0;
    }
    wl1r = WR2500;
    wl1i = WI2500;
    j0 = mh;
    j1 = j0 + m;
    j2 = j1 + m;
    j3 = j2 + m;
    x0r = a[(j0 - 2) as usize] - a[(j2 - 1) as usize];
    x0i = a[(j0 - 1) as usize] + a[(j2 - 2) as usize];
    x1r = a[(j0 - 2) as usize] + a[(j2 - 1) as usize];
    x1i = a[(j0 - 1) as usize] - a[(j2 - 2) as usize];
    x2r = a[(j1 - 2) as usize] - a[(j3 - 1) as usize];
    x2i = a[(j1 - 1) as usize] + a[(j3 - 2) as usize];
    x3r = a[(j1 - 2) as usize] + a[(j3 - 1) as usize];
    x3i = a[(j1 - 1) as usize] - a[(j3 - 2) as usize];
    y0r = wk1r * x0r - wk1i * x0i;
    y0i = wk1r * x0i + wk1i * x0r;
    y2r = wd1r * x2r - wd1i * x2i;
    y2i = wd1r * x2i + wd1i * x2r;
    a[(j0 - 2) as usize] = y0r + y2r;
    a[(j0 - 1) as usize] = y0i + y2i;
    a[(j1 - 2) as usize] = y0r - y2r;
    a[(j1 - 1) as usize] = y0i - y2i;
    y0r = wk3r * x1r + wk3i * x1i;
    y0i = wk3r * x1i - wk3i * x1r;
    y2r = wd3r * x3r + wd3i * x3i;
    y2i = wd3r * x3i - wd3i * x3r;
    a[(j2 - 2) as usize] = y0r + y2r;
    a[(j2 - 1) as usize] = y0i + y2i;
    a[(j3 - 2) as usize] = y0r - y2r;
    a[(j3 - 1) as usize] = y0i - y2i;
    x0r = a[j0 as usize] - a[(j2 + 1) as usize];
    x0i = a[(j0 + 1) as usize] + a[j2 as usize];
    x1r = a[j0 as usize] + a[(j2 + 1) as usize];
    x1i = a[(j0 + 1) as usize] - a[j2 as usize];
    x2r = a[j1 as usize] - a[(j3 + 1) as usize];
    x2i = a[(j1 + 1) as usize] + a[j3 as usize];
    x3r = a[j1 as usize] + a[(j3 + 1) as usize];
    x3i = a[(j1 + 1) as usize] - a[j3 as usize];
    y0r = wl1r * x0r - wl1i * x0i;
    y0i = wl1r * x0i + wl1i * x0r;
    y2r = wl1i * x2r - wl1r * x2i;
    y2i = wl1i * x2i + wl1r * x2r;
    a[j0 as usize] = y0r + y2r;
    a[(j0 + 1) as usize] = y0i + y2i;
    a[j1 as usize] = y0r - y2r;
    a[(j1 + 1) as usize] = y0i - y2i;
    y0r = wl1i * x1r - wl1r * x1i;
    y0i = wl1i * x1i + wl1r * x1r;
    y2r = wl1r * x3r - wl1i * x3i;
    y2i = wl1r * x3i + wl1i * x3r;
    a[j2 as usize] = y0r - y2r;
    a[(j2 + 1) as usize] = y0i - y2i;
    a[j3 as usize] = y0r + y2r;
    a[(j3 + 1) as usize] = y0i + y2i;
    x0r = a[(j0 + 2) as usize] - a[(j2 + 3) as usize];
    x0i = a[(j0 + 3) as usize] + a[(j2 + 2) as usize];
    x1r = a[(j0 + 2) as usize] + a[(j2 + 3) as usize];
    x1i = a[(j0 + 3) as usize] - a[(j2 + 2) as usize];
    x2r = a[(j1 + 2) as usize] - a[(j3 + 3) as usize];
    x2i = a[(j1 + 3) as usize] + a[(j3 + 2) as usize];
    x3r = a[(j1 + 2) as usize] + a[(j3 + 3) as usize];
    x3i = a[(j1 + 3) as usize] - a[(j3 + 2) as usize];
    y0r = wd1i * x0r - wd1r * x0i;
    y0i = wd1i * x0i + wd1r * x0r;
    y2r = wk1i * x2r - wk1r * x2i;
    y2i = wk1i * x2i + wk1r * x2r;
    a[(j0 + 2) as usize] = y0r + y2r;
    a[(j0 + 3) as usize] = y0i + y2i;
    a[(j1 + 2) as usize] = y0r - y2r;
    a[(j1 + 3) as usize] = y0i - y2i;
    y0r = wd3i * x1r + wd3r * x1i;
    y0i = wd3i * x1i - wd3r * x1r;
    y2r = wk3i * x3r + wk3r * x3i;
    y2i = wk3i * x3i - wk3r * x3r;
    a[(j2 + 2) as usize] = y0r + y2r;
    a[(j2 + 3) as usize] = y0i + y2i;
    a[(j3 + 2) as usize] = y0r - y2r;
    a[(j3 + 3) as usize] = y0i - y2i;
}
